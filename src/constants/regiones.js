// Normaliza para comparar nombres geográficos: sin tildes, sin apóstrofes
// (O'Higgins = Ohiggins), sin signos, minúsculas y espacios simples.
export function normalizarGeo(s) {
  return String(s ?? "")
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .replace(/['’´`]/g, "")
    .replace(/[^a-zA-Z0-9 ]/g, " ")
    .replace(/\s+/g, " ")
    .trim()
    .toLowerCase();
}

// Todos los nombres con que se conoce una comuna de la lista (el de la lista primero).
export function nombresDeComuna(comuna) {
  const c = String(comuna ?? "").trim();
  return c ? [c, ...(ALIAS_COMUNAS[c] || [])] : [];
}

const COMUNA_POR_NOMBRE = (() => {
  const m = new Map();
  for (const comunas of Object.values(REGIONES_CHILE)) {
    for (const c of comunas) {
      for (const n of nombresDeComuna(c)) {
        const k = normalizarGeo(n);
        if (!m.has(k)) m.set(k, c);
      }
    }
  }
  return m;
})();

// Comuna de la lista a la que corresponde un texto (nombre de la lista o alias,
// sin importar tildes ni mayúsculas). null si no calza con ninguna.
export function buscarComuna(texto) {
  return COMUNA_POR_NOMBRE.get(normalizarGeo(texto)) ?? null;
}

// Región de una comuna (por nombre de la lista o alias). null si no se conoce.
export function regionDeComuna(comuna) {
  const c = buscarComuna(comuna);
  if (!c) return null;
  return Object.keys(REGIONES_CHILE).find((r) => REGIONES_CHILE[r].includes(c)) ?? null;
}

// Filtro para los react-select de comuna: por términos sueltos (como el
// buscador general) sobre cualquiera de los nombres de la comuna, así
// "puerto natales" encuentra Natales y "la calera" encuentra Calera.
export function filtrarOpcionComuna(option, inputValue) {
  const q = normalizarGeo(inputValue);
  if (!q) return true;
  const terminos = q.split(" ").filter(Boolean);
  const nombres = nombresDeComuna(option?.value ?? option?.label).map(normalizarGeo);
  if (!nombres.length) nombres.push(normalizarGeo(option?.label));
  return nombres.some((n) => terminos.every((t) => n.includes(t)));
}

// Localidad de un tarifario de courier (p. ej. las localidades Starken de una
// región) que corresponde a una comuna: por el nombre tal cual, por sus alias,
// por la agrupación del Gran Santiago y, si no, por la única localidad que
// empiece con el nombre ("Rinconada" → "RINCONADA DE SILVA" solo si no hay
// otra). Devuelve el nombre tal como viene en la lista, o null.
export function buscarLocalidadFlete(comuna, localidades) {
  const lista = Array.isArray(localidades) ? localidades : [];
  const texto = String(comuna ?? "").trim();
  if (!lista.length || !texto) return null;
  const canon = buscarComuna(texto);
  const candidatos = [...new Set([texto, ...(canon ? nombresDeComuna(canon) : [])])];
  if (canon && COMUNAS_GRAN_SANTIAGO.has(canon)) candidatos.push("Santiago");
  const normLista = lista.map((l) => normalizarGeo(l));
  for (const cand of candidatos) {
    const i = normLista.indexOf(normalizarGeo(cand));
    if (i >= 0) return lista[i];
  }
  for (const cand of candidatos) {
    const n = normalizarGeo(cand);
    const idx = normLista.map((l, i) => (l.startsWith(n + " ") ? i : -1)).filter((i) => i >= 0);
    if (idx.length === 1) return lista[idx[0]];
  }
  return null;
}
