-- Inventario por SUCURSAL y traslados entre sucursales (pedido 2026-11-02).
--
-- Modelo:
--   · productos.stock sigue siendo el TOTAL (lo leen Gestión de compras, el
--     portal, la simulación de facturación, etc. y lo sincroniza Bsale).
--   · inventario_stock_sucursales reparte ese total por sucursal propia
--     (Casa Matriz, bodega, local…). Invariante que mantiene el backend:
--       productos.stock = Σ stock por sucursal + unidades en tránsito.
--   · inventario_traslados / inventario_traslado_lineas: un traslado sale de
--     la sucursal de origen (queda «en tránsito»), y al recibirlo entra en la
--     de destino. Si llega menos de lo enviado, la diferencia queda como
--     ajuste negativo en el libro (merma en tránsito), auditable.
--   · inventario_movimientos gana la sucursal, el traslado y el stock
--     resultante EN LA SUCURSAL (stock_resultante sigue siendo el total).
--
-- Bsale (donde Amsodent factura) tiene UNA sola sucursal (Casa Matriz, id 1):
-- la sincronización aplica sus diferencias a la sucursal principal del sistema
-- (es_principal). bsale_office_id queda preparado por si Bsale suma sucursales.
--
-- Re-ejecutable (if not exists / on conflict).

create table if not exists inventario_sucursales (
  id bigint generated by default as identity primary key,
  nombre text not null,
  direccion text,
  comuna text,
  activa boolean not null default true,
  -- La principal recibe los movimientos sin sucursal explícita y las
  -- diferencias de la sincronización con Bsale. Siempre hay exactamente una.
  es_principal boolean not null default false,
  -- id de la sucursal en Bsale (/offices.json), si corresponde a una.
  bsale_office_id integer,
  orden integer not null default 0,
  created_at timestamptz not null default now()
);

create unique index if not exists inventario_sucursales_nombre_idx
  on inventario_sucursales (lower(nombre));
create unique index if not exists inventario_sucursales_principal_idx
  on inventario_sucursales (es_principal) where es_principal;

comment on table inventario_sucursales is
  'Sucursales / bodegas propias del módulo Inventario. La principal (es_principal) recibe la sincronización de Bsale y los movimientos sin sucursal.';

-- Casa Matriz: la única sucursal real al 2026-11-02 (Bsale office 1).
insert into inventario_sucursales (nombre, direccion, comuna, activa, es_principal, bsale_office_id, orden)
select 'Casa Matriz', '1 Mayo 45', 'San Bernardo', true, true, 1, 0
where not exists (select 1 from inventario_sucursales);

create table if not exists inventario_stock_sucursales (
  producto_id bigint not null references productos (id) on delete cascade,
  sucursal_id bigint not null references inventario_sucursales (id) on delete restrict,
  stock numeric not null default 0,
  updated_at timestamptz not null default now(),
  primary key (producto_id, sucursal_id)
);

create index if not exists inventario_stock_sucursales_sucursal_idx
  on inventario_stock_sucursales (sucursal_id) where stock <> 0;

comment on table inventario_stock_sucursales is
  'Stock por sucursal propia. Lo escribe solo el backend del módulo Inventario; productos.stock = suma de sucursales + en tránsito.';

-- El stock que ya existía estaba todo en la Casa Matriz.
insert into inventario_stock_sucursales (producto_id, sucursal_id, stock)
select p.id, s.id, p.stock
from productos p
cross join inventario_sucursales s
where s.es_principal and coalesce(p.stock, 0) <> 0
on conflict (producto_id, sucursal_id) do nothing;

create table if not exists inventario_traslados (
  id bigint generated by default as identity primary key,
  origen_id bigint not null references inventario_sucursales (id),
  destino_id bigint not null references inventario_sucursales (id),
  -- en_transito: salió del origen y aún no se recibe.
  -- recibido: entró al destino (cantidad_recibida por línea).
  -- anulado: se anuló en tránsito y el stock volvió al origen.
  estado text not null default 'en_transito'
    check (estado in ('en_transito', 'recibido', 'anulado')),
  motivo text,
  referencia text,
  usuario_email text,
  created_at timestamptz not null default now(),
  recibido_por text,
  recibido_at timestamptz,
  nota_recepcion text,
  anulado_por text,
  anulado_at timestamptz,
  motivo_anulacion text,
  check (origen_id <> destino_id)
);

create index if not exists inventario_traslados_estado_idx
  on inventario_traslados (estado, created_at desc);

create table if not exists inventario_traslado_lineas (
  id bigint generated by default as identity primary key,
  traslado_id bigint not null references inventario_traslados (id) on delete cascade,
  producto_id bigint not null references productos (id),
  -- SKU y nombre copiados al momento del traslado (historial estable).
  sku text,
  nombre text,
  cantidad numeric not null check (cantidad > 0),
  cantidad_recibida numeric
);

create index if not exists inventario_traslado_lineas_traslado_idx
  on inventario_traslado_lineas (traslado_id);
create index if not exists inventario_traslado_lineas_producto_idx
  on inventario_traslado_lineas (producto_id);

comment on table inventario_traslados is
  'Traslados de stock entre sucursales propias: en_transito → recibido | anulado. Las líneas van en inventario_traslado_lineas.';

-- Guía de traslado interno emitida en Bsale para este traslado. Bsale mueve el
-- stock entre SUS sucursales con una guía de despacho tipo «Traslados internos»
-- (officeId → destinationOfficeId): sale del origen al emitirla y entra al
-- destino cuando el destino la recepciona (shipping.received = 1).
alter table inventario_traslados
  add column if not exists bsale_id bigint,              -- id del despacho (/shippings/{id}) → trae `received`
  add column if not exists bsale_doc_id bigint,          -- id del documento (la guía) en Bsale
  add column if not exists bsale_numero text,            -- folio de la guía
  add column if not exists bsale_url text,               -- PDF / vista pública
  add column if not exists bsale_emitido_at timestamptz,
  add column if not exists bsale_emitido_por text,
  add column if not exists bsale_recibido_at timestamptz; -- cuándo Bsale la marcó recepcionada (lo detecta la sincronización)

create index if not exists inventario_traslados_bsale_idx
  on inventario_traslados (bsale_id) where bsale_id is not null;

-- Libro de movimientos: sucursal, traslado y stock resultante en la sucursal.
alter table inventario_movimientos
  add column if not exists sucursal_id bigint references inventario_sucursales (id),
  add column if not exists traslado_id bigint references inventario_traslados (id),
  add column if not exists stock_resultante_sucursal numeric;

create index if not exists inventario_movimientos_sucursal_idx
  on inventario_movimientos (sucursal_id, created_at desc);
create index if not exists inventario_movimientos_traslado_idx
  on inventario_movimientos (traslado_id) where traslado_id is not null;

-- Tipos nuevos: traslado_salida (sale del origen) y traslado_entrada (entra al
-- destino, o vuelve al origen al anular). Ninguno cambia el total.
alter table inventario_movimientos drop constraint if exists inventario_movimientos_tipo_check;
alter table inventario_movimientos
  add constraint inventario_movimientos_tipo_check
  check (tipo in ('entrada', 'salida', 'ajuste', 'traslado_salida', 'traslado_entrada'));

-- Los movimientos anteriores a las sucursales ocurrieron todos en la principal.
update inventario_movimientos m
  set sucursal_id = s.id
  from inventario_sucursales s
  where s.es_principal and m.sucursal_id is null;

comment on column inventario_movimientos.sucursal_id is
  'Sucursal donde ocurrió el movimiento (la principal para los anteriores a 2026-11).';
comment on column inventario_movimientos.stock_resultante_sucursal is
  'Stock de la sucursal después del movimiento (stock_resultante sigue siendo el total del producto).';
