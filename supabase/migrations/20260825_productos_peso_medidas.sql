  alto  = coalesce(v.alto,  p.alto),
  metro_cubico = case
    when coalesce(v.alto, p.alto) > 0
     and coalesce(v.largo, p.largo) > 0
     and coalesce(v.ancho, p.ancho) > 0
    then round((coalesce(v.alto, p.alto) * coalesce(v.largo, p.largo) * coalesce(v.ancho, p.ancho))::numeric, 2)
    else p.metro_cubico
  end
